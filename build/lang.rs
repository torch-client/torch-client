use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const ENGLISH: &str = "en_us";
const RUSSIAN: &str = "ru_ru";

pub(crate) fn run() {
    let manifest = std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is unset");
    let out = std::env::var_os("OUT_DIR").expect("OUT_DIR is unset");
    let russian = std::env::var_os("CARGO_FEATURE_MULTI_LANGUAGE").is_some();
    let source = generate(&Path::new(&manifest).join("lang"), russian);
    let path = Path::new(&out).join("lang_tables.rs");
    std::fs::write(&path, source).unwrap_or_else(|e| panic!("writing {}: {e}", path.display()));
}

pub(crate) fn generate(dir: &Path, russian: bool) -> String {
    let english = read_language(&dir.join(ENGLISH), true);
    check_plurals(&english);
    let mut out =
        String::from("// Generated by build/lang.rs from lang/*/*.json. Edit those instead.\n\n");
    assert!(
        english.len() < usize::from(u16::MAX),
        "lang/{ENGLISH} has more keys than a Key can index"
    );
    emit(&mut out, "KEYS", english.keys().map(String::as_str));
    emit(
        &mut out,
        "EN",
        english.values().map(|(text, _)| text.as_str()),
    );
    let russian_table = read_language(&dir.join(RUSSIAN), false);
    check_plurals(&russian_table);
    for (key, (_, file)) in &russian_table {
        if !english.contains_key(key) {
            panic!("{}: `{key}` is not in lang/{ENGLISH}", file.display());
        }
    }
    if russian {
        emit(
            &mut out,
            "RU",
            english
                .iter()
                .map(|(key, (text, _))| match russian_table.get(key) {
                    Some((t, _)) if !t.is_empty() => t.as_str(),
                    _ => text.as_str(),
                }),
        );
    }
    out
}

const PLURAL_FORMS: [&str; 3] = ["one", "few", "many"];

fn check_plurals(table: &BTreeMap<String, (String, PathBuf)>) {
    for (key, (_, file)) in table {
        let Some((base, form)) = key.rsplit_once('.') else {
            continue;
        };
        if !PLURAL_FORMS.contains(&form) {
            continue;
        }
        for want in PLURAL_FORMS {
            if !table.contains_key(&format!("{base}.{want}")) {
                panic!(
                    "{}: plural `{base}` has `.{form}` but no `.{want}`",
                    file.display()
                );
            }
        }
    }
}

fn emit<'a>(out: &mut String, name: &str, items: impl ExactSizeIterator<Item = &'a str>) {
    let _ = writeln!(out, "pub(crate) const {name}: [&str; {}] = [", items.len());
    for item in items {
        let _ = writeln!(out, "    {item:?},");
    }
    out.push_str("];\n");
}

fn read_language(dir: &Path, required: bool) -> BTreeMap<String, (String, PathBuf)> {
    let mut table = BTreeMap::new();
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) if !required && e.kind() == std::io::ErrorKind::NotFound => return table,
        Err(e) => panic!("reading {}: {e}", dir.display()),
    };
    let mut files: Vec<PathBuf> = entries
        .map(|e| {
            e.unwrap_or_else(|e| panic!("reading {}: {e}", dir.display()))
                .path()
        })
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    files.sort();
    for file in files {
        let area = file
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or_else(|| panic!("{}: the file name is not UTF-8", file.display()))
            .to_owned();
        let text = std::fs::read_to_string(&file)
            .unwrap_or_else(|e| panic!("reading {}: {e}", file.display()));
        let pairs = parse(&text).unwrap_or_else(|e| panic!("{}: {e}", file.display()));
        for (key, value) in pairs {
            let Some(value) = value else {
                panic!("{}: the value of `{key}` is not a string", file.display());
            };
            check_key(&file, &area, &key);
            if let Some((_, first)) = table.get(&key) {
                panic!("{}: `{key}` is also in {}", file.display(), first.display());
            }
            table.insert(key, (value, file.clone()));
        }
    }
    table
}

fn check_key(file: &Path, area: &str, key: &str) {
    let well_formed = key
        .split('.')
        .all(|seg| !seg.is_empty() && seg.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'));
    if !well_formed {
        panic!(
            "{}: `{key}` is not dot-separated segments of A-Z, a-z, 0-9 and _",
            file.display()
        );
    }
    if key.split('.').next() != Some(area) {
        panic!(
            "{}: `{key}` does not start with `{area}.`, the file's area",
            file.display()
        );
    }
}

fn parse(text: &str) -> Result<Vec<(String, Option<String>)>, String> {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let mut p = Parser {
        bytes: text.as_bytes(),
        text,
        at: 0,
    };
    let mut pairs = Vec::new();
    p.ws();
    p.expect(b'{')?;
    p.ws();
    if p.peek() == Some(b'}') {
        p.at += 1;
    } else {
        loop {
            p.ws();
            let key = p.string()?;
            p.ws();
            p.expect(b':')?;
            p.ws();
            let value = if p.peek() == Some(b'"') {
                Some(p.string()?)
            } else {
                p.skip_value()?;
                None
            };
            pairs.push((key, value));
            p.ws();
            match p.next() {
                Some(b',') => continue,
                Some(b'}') => break,
                _ => return Err(p.error("expected `,` or `}`")),
            }
        }
    }
    p.ws();
    if p.at != p.bytes.len() {
        return Err(p.error("text after the closing `}`"));
    }
    Ok(pairs)
}

struct Parser<'a> {
    bytes: &'a [u8],
    text: &'a str,
    at: usize,
}

impl Parser<'_> {
    fn error(&self, what: &str) -> String {
        let line = self.bytes[..self.at.min(self.bytes.len())]
            .iter()
            .filter(|&&b| b == b'\n')
            .count()
            + 1;
        format!("line {line}: {what}")
    }

    fn peek(&self) -> Option<u8> {
        self.bytes.get(self.at).copied()
    }

    fn next(&mut self) -> Option<u8> {
        let b = self.peek()?;
        self.at += 1;
        Some(b)
    }

    fn ws(&mut self) {
        while matches!(self.peek(), Some(b' ' | b'\t' | b'\n' | b'\r')) {
            self.at += 1;
        }
    }

    fn expect(&mut self, want: u8) -> Result<(), String> {
        if self.next() == Some(want) {
            Ok(())
        } else {
            Err(self.error(&format!("expected `{}`", want as char)))
        }
    }

    fn hex4(&mut self) -> Result<u32, String> {
        let digits = self
            .bytes
            .get(self.at..self.at + 4)
            .ok_or_else(|| self.error("a short \\u escape"))?;
        let mut value = 0;
        for &b in digits {
            let digit = (b as char)
                .to_digit(16)
                .ok_or_else(|| self.error("a \\u escape that is not four hex digits"))?;
            value = value * 16 + digit;
        }
        self.at += 4;
        Ok(value)
    }

    fn string(&mut self) -> Result<String, String> {
        self.expect(b'"')?;
        let mut out = String::new();
        loop {
            let start = self.at;
            while matches!(self.peek(), Some(b) if b != b'"' && b != b'\\' && b >= 0x20) {
                self.at += 1;
            }
            out.push_str(&self.text[start..self.at]);
            match self.next() {
                Some(b'"') => return Ok(out),
                Some(b'\\') => {}
                Some(_) => return Err(self.error("a control character inside a string")),
                None => return Err(self.error("a string that never ends")),
            }
            let c = match self.next() {
                Some(b'"') => '"',
                Some(b'\\') => '\\',
                Some(b'/') => '/',
                Some(b'b') => '\u{8}',
                Some(b'f') => '\u{c}',
                Some(b'n') => '\n',
                Some(b'r') => '\r',
                Some(b't') => '\t',
                Some(b'u') => {
                    let hi = self.hex4()?;
                    let code = if (0xD800..0xDC00).contains(&hi) {
                        if self.next() != Some(b'\\') || self.next() != Some(b'u') {
                            return Err(
                                self.error("a high surrogate with no low surrogate after it")
                            );
                        }
                        let lo = self.hex4()?;
                        if !(0xDC00..0xE000).contains(&lo) {
                            return Err(
                                self.error("a high surrogate with no low surrogate after it")
                            );
                        }
                        0x10000 + ((hi - 0xD800) << 10) + (lo - 0xDC00)
                    } else {
                        hi
                    };
                    char::from_u32(code).ok_or_else(|| self.error("a lone low surrogate"))?
                }
                _ => return Err(self.error("an unknown escape")),
            };
            out.push(c);
        }
    }

    fn skip_value(&mut self) -> Result<(), String> {
        let mut depth = 0usize;
        loop {
            match self.peek() {
                None => return Err(self.error("a value that never ends")),
                Some(b'"') => {
                    self.string()?;
                    continue;
                }
                Some(b'{' | b'[') => depth += 1,
                Some(b'}' | b']') if depth > 0 => depth -= 1,
                Some(b',' | b'}') if depth == 0 => return Ok(()),
                _ => {}
            }
            self.at += 1;
        }
    }
}
