#!/usr/bin/env python3
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "reference/minecraft-26.2/net/minecraft/util/datafix/fixes/BlockStateData.java"
OUT = ROOT / "mods/litematica/legacy_blocks.lua"

FILTER_ME = "%%FILTER_ME%%"

RENAMES = [
    {"minecraft:purple_shulker_box": "minecraft:shulker_box"},
    {"minecraft:flowing_water": "minecraft:water", "minecraft:flowing_lava": "minecraft:lava"},
    {"minecraft:melon_block": "minecraft:melon"},
    {
        "minecraft:portal": "minecraft:nether_portal",
        "minecraft:oak_bark": "minecraft:oak_wood",
        "minecraft:spruce_bark": "minecraft:spruce_wood",
        "minecraft:birch_bark": "minecraft:birch_wood",
        "minecraft:jungle_bark": "minecraft:jungle_wood",
        "minecraft:acacia_bark": "minecraft:acacia_wood",
        "minecraft:dark_oak_bark": "minecraft:dark_oak_wood",
        "minecraft:mob_spawner": "minecraft:spawner",
    },
    {
        "minecraft:stone_slab": "minecraft:smooth_stone_slab",
        "minecraft:sign": "minecraft:oak_sign",
        "minecraft:wall_sign": "minecraft:oak_wall_sign",
    },
    {"minecraft:grass_path": "minecraft:dirt_path"},
    {"minecraft:grass": "minecraft:short_grass"},
    {"minecraft:chain": "minecraft:iron_chain"},
]

LEAVES = {f"minecraft:{w}_leaves" for w in ("oak", "spruce", "birch", "jungle", "acacia", "dark_oak")}
WALLS = {"minecraft:cobblestone_wall", "minecraft:mossy_cobblestone_wall"}

def strings(args: str) -> list[str]:
    return re.findall(r'"([^"]*)"', args)

def pairs(args: str) -> dict[str, str]:
    s = strings(args)
    if len(s) % 2:
        sys.exit(f"odd Map.of arguments: {args}")
    return dict(zip(s[0::2], s[1::2]))

def upgrade(name: str, props: dict[str, str]) -> tuple[str, dict[str, str]]:
    props = dict(props)
    for table in RENAMES:
        name = table.get(name, name)
    if name in LEAVES:
        persistent = props.pop("decayable", "") == "false"
        props.pop("check_decay", None)
        props["persistent"] = "true" if persistent else "false"
        props["distance"] = "7"
    if name in WALLS:
        for side in ("east", "west", "north", "south"):
            if side in props:
                props[side] = "low" if props[side] == "true" else "none"
    if name == "minecraft:redstone_wire":
        e, w, n, s = (props.get(k, "none") for k in ("east", "west", "north", "south"))
        on = lambda v: v != "none"
        ew, ns = on(e) or on(w), on(n) or on(s)
        props["east"] = "side" if not on(e) and not ns else e
        props["west"] = "side" if not on(w) and not ns else w
        props["north"] = "side" if not on(n) and not ew else n
        props["south"] = "side" if not on(s) and not ew else s
    if name == "minecraft:cauldron":
        if props.get("level", "0") == "0":
            props = {}
        else:
            name = "minecraft:water_cauldron"
    return name, props

def state(name: str, props: dict[str, str]) -> str:
    if not props:
        return name
    return name + "[" + ",".join(f"{k}={v}" for k, v in sorted(props.items())) + "]"

def main() -> None:
    text = SRC.read_text()
    consts = {}
    for m in re.finditer(r"Map<String, String> (\w+) = Map\.of\(([^;]*)\);", text):
        consts[m.group(1)] = pairs(m.group(2))
    entries: dict[int, str] = {}
    defaults: dict[int, int] = {}
    reg = re.compile(r'register\((\d+), create\("([^"]+)"(?:, (Map\.of\([^)]*\)|\w+))?\)')
    for m in reg.finditer(text):
        lid, name, arg = int(m.group(1)), m.group(2), m.group(3)
        if arg is None:
            props = {}
        elif arg.startswith("Map.of("):
            props = pairs(arg)
        elif arg in consts:
            props = consts[arg]
        else:
            sys.exit(f"unknown properties constant {arg} at id {lid}")
        entries[lid] = state(name, props) if name == FILTER_ME else state(*upgrade(name, props))
        defaults.setdefault(lid >> 4, lid)
    count = len(re.findall(r"^\s*register\(\d+,", text, re.M))
    if count != len(entries):
        sys.exit(f"parsed {len(entries)} of {count} register lines")

    out = [
        "-- Generated by tools/gen_legacy_blocks.py from vanilla 26.2's",
        "-- BlockStateData (the 1.13 flattening table) and the block state fixers",
        "-- DataFixers runs after it. Do not edit by hand.",
        "--",
        "-- states[id << 4 | meta]: the block state. %%FILTER_ME%% is vanilla's",
        "-- marker for air unless a block entity says otherwise (the skulls).",
        "-- defaults[id]: the first value registered for block id, which vanilla's",
        "-- finalizeMaps uses for a meta the table has no entry for.",
        "local states = {",
    ]
    for lid in sorted(entries):
        out.append(f'  [{lid}] = "{entries[lid]}",')
    out.append("}")
    out.append("local defaults = {")
    for bid in sorted(defaults):
        out.append(f"  [{bid}] = {defaults[bid]},")
    out.append("}")
    out.append("return { states = states, defaults = defaults }")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{len(entries)} states, {len(defaults)} blocks -> {OUT.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
