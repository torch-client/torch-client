#!/usr/bin/env python3

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_ap = argparse.ArgumentParser(description="Generate push_reactions.rs on stdout.")
_ap.add_argument("--version", default="26.2",
                 help="reference/minecraft-<version> tree to read (default 26.2)")
MC_DIR = Path("reference") / f"minecraft-{_ap.parse_args().version}" / "net/minecraft"
BLOCK = ROOT / MC_DIR / "world/level/block"

def statements(body):
    out, depth, start = [], 0, 0
    for i, c in enumerate(body):
        if c in "({":
            depth += 1
        elif c in ")}":
            depth -= 1
        elif c == ";" and depth == 0:
            out.append(body[start:i].strip())
            start = i + 1
    return out

def helpers(src):
    found = {}
    for m in re.finditer(r"(?:private|public) static [\w.<>?]+ (\w+)\([^)]*\) \{", src):
        depth, i = 1, m.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(src[i], 0)
            i += 1
        reaction = re.findall(r"pushReaction\(PushReaction\.(\w+)\)", src[m.end():i])
        if reaction:
            found[m.group(1)] = reaction[-1]
    return found

COLORS = ("white", "orange", "magenta", "light_blue", "yellow", "lime", "pink", "gray",
          "light_gray", "cyan", "purple", "blue", "brown", "green", "red", "black")
WEATHER_PREFIXES = ("", "exposed_", "weathered_", "oxidized_", "waxed_", "waxed_exposed_",
                    "waxed_weathered_", "waxed_oxidized_")

def id_tables():
    ids, colors, copper = {}, {}, {}
    for holder in ("BlockIds", "BlockItemIds"):
        text = (ROOT / MC_DIR / "references" / (holder + ".java")).read_text()
        for const, name in re.findall(
                r"\b([A-Z][A-Z0-9_]*) = (?:BlockItemId\.)?create\(\"([a-z0-9_]+)\"", text):
            ids[holder + "." + const] = [name]
        for const, base in re.findall(r"\b([A-Z][A-Z0-9_]*) = createSimpleColored\(\"(\w+)\"\)", text):
            colors[holder + "." + const] = [c + "_" + base for c in COLORS]
        for const, base in re.findall(r"\b([A-Z][A-Z0-9_]*) = createSimpleCopper\(\"(\w+)\"\)", text):
            copper[holder + "." + const] = [p + base for p in WEATHER_PREFIXES]
        special = re.search(r"COPPER_BLOCK_SPECIAL_NAMES = new WeatheringCopperCollection\.ByState"
                            r"\(\"(\w+)\", \"(\w+)\", \"(\w+)\", \"(\w+)\"\)", text)
        if special:
            copper[holder + ".COPPER_BLOCK"] = [p + n for p, n in zip(WEATHER_PREFIXES, special.groups() * 2)]
    return ids, colors, copper

def main():
    src = (BLOCK / "Blocks.java").read_text()
    helper = helpers(src)
    static = src[src.index("   static {"):]
    ids, colors, copper = id_tables()
    names_of, reaction = {}, {}
    for st in statements(static[static.index("{") + 1:]):
        m = re.match(r"(\w+) = ([\w.]+)\(((?:BlockIds|BlockItemIds)\.\w+)", st)
        if not m:
            continue
        const, call, ref = m.groups()
        if call == "ColorCollection.registerBlocks":
            names = colors[ref]
        elif call == "WeatheringCopperCollection.registerBlocks":
            names = copper[ref]
        else:
            names = ids[ref]
        names_of[const] = names
        direct = re.findall(r"pushReaction\(PushReaction\.(\w+)\)", st)
        copy = re.search(r"of(?:Full|Legacy)Copy\((?:\(BlockBehaviour\))?(\w+)(?:\.weathering\(\)\.pick\(\w+\))?\)", st)
        stair = re.match(r"\w+ = register(?:Legacy)?(?:Stair|Slab|Wall)\([\w.]+, (\w+)\)", st)
        used = [h for h in helper if re.search(r"\b%s\(" % h, st)]
        if direct:
            r = direct[-1]
        elif used:
            r = helper[used[0]]
        elif copy:
            r = reaction.get(copy.group(1), "NORMAL")
        elif stair:
            r = reaction.get(stair.group(1), "NORMAL")
        else:
            r = "NORMAL"
        reaction[const] = r

    bet = (BLOCK / "entity/BlockEntityTypes.java").read_text()
    entity = sorted({n for c in re.findall(r"Blocks\.(\w+)", bet) for n in names_of.get(c, [])})

    by = {}
    for const, r in reaction.items():
        if r != "NORMAL":
            by.setdefault(r, []).extend(names_of[const])

    w = sys.stdout.write
    w("//! Generated by `tools/gen_push_reactions.py` from Blocks.java and BlockEntityTypes.java.\n\n")
    w("use super::PushReaction;\n\n")
    w("/// `BlockBehaviour.getPistonPushReaction`, by block id.\n")
    w("pub(super) fn push_reaction(id: &str) -> PushReaction {\n    match id {\n")
    for r in sorted(by):
        names = sorted(by[r])
        w("        " + "\n        | ".join('"%s"' % n for n in names))
        w(" => PushReaction::%s,\n" % r.title().replace("_", ""))
    w("        _ => PushReaction::Normal,\n    }\n}\n\n")
    w("/// `BlockStateBase.hasBlockEntity`, by block id.\n")
    w("pub(super) fn has_block_entity(id: &str) -> bool {\n    matches!(\n        id,\n        ")
    w("\n            | ".join('"%s"' % n for n in entity))
    w("\n    )\n}\n")

main()
